#include "../aes.h"
#include "../aes-cmac.h"
#include <stdio.h>
#include <string.h>

/*
 * Tests the aes_cmac function with the test vectors in chapter 4 of RFC 4493.
 */
int main(int argc, char **argv) {
  unsigned char mac[16];

  const unsigned char k[16] = {
    0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6,
    0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c
  };

  /* Example 1: len = 0 */
  {
    const unsigned char mac1[16] = {
      0xbb, 0x1d, 0x69, 0x29, 0xe9, 0x59, 0x37, 0x28,
      0x7f, 0xa3, 0x7d, 0x12, 0x9b, 0x75, 0x67, 0x46
    };
    aes_cmac(mac, k, 0, 0);
    if (memcmp(mac, mac1, sizeof(mac))) {
      fputs("aes_cmac() failed example 1\n", stderr);
      return 1;
    }
  }

  /* Example 2: len = 16 */
  {
    const unsigned char m2[16] = {
      0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
      0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a
    };
    const unsigned char mac2[16] = {
      0x07, 0x0a, 0x16, 0xb4, 0x6b, 0x4d, 0x41, 0x44,
      0xf7, 0x9b, 0xdd, 0x9d, 0xd0, 0x4a, 0x28, 0x7c
    };
    aes_cmac(mac, k, m2, sizeof(m2));
    if (memcmp(mac, mac2, sizeof(mac))) {
      fputs("aes_cmac() failed example 2\n", stderr);
      return 1;
    }
  }

  /* Example 3: len = 40 */
  {
    const unsigned char m3[40] = {
      0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
      0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a,
      0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c,
      0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf, 0x8e, 0x51,
      0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4, 0x11
    };
    const unsigned char mac3[16] = {
      0xdf, 0xa6, 0x67, 0x47, 0xde, 0x9a, 0xe6, 0x30,
      0x30, 0xca, 0x32, 0x61, 0x14, 0x97, 0xc8, 0x27
    };
    aes_cmac(mac, k, m3, sizeof(m3));
    if (memcmp(mac, mac3, sizeof(mac))) {
      fputs("aes_cmac() failed example 3\n", stderr);
      return 1;
    }
  }

  /* Example 4: len = 64 */
  {
    const unsigned char m4[64] = {
      0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
      0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a,
      0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c,
      0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf, 0x8e, 0x51,
      0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4, 0x11,
      0xe5, 0xfb, 0xc1, 0x19, 0x1a, 0x0a, 0x52, 0xef,
      0xf6, 0x9f, 0x24, 0x45, 0xdf, 0x4f, 0x9b, 0x17,
      0xad, 0x2b, 0x41, 0x7b, 0xe6, 0x6c, 0x37, 0x10
    };
    const unsigned char mac4[16] = {
      0x51, 0xf0, 0xbe, 0xbf, 0x7e, 0x3b, 0x9d, 0x92,
      0xfc, 0x49, 0x74, 0x17, 0x79, 0x36, 0x3c, 0xfe
    };
    aes_cmac(mac, k, m4, sizeof(m4));
    if (memcmp(mac, mac4, sizeof(mac))) {
      fputs("aes_cmac() failed example 4\n", stderr);
      return 1;
    }
  }

  return 0;
}
